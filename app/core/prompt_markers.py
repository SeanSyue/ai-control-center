"""AICC 自己寫過的字，**拿來比對用的**。

這裡收三種：寫進提示詞的開場白、從 AI 回覆裡認出來的關鍵字、
以及這個 repo 自己那幾份文件的格式。三種的共同點是——
**它們比對的對象是 AICC 或它的 AI 寫出來的東西，不是使用者輸入。**
翻掉任何一個，比對就靜靜地失效。

## 這些**不是介面文字**，翻掉它們東西會壞

`session_panel` 要從一段對話紀錄裡猜出「這個對話在做什麼」，而那段紀錄的
開頭通常是 **AICC 自己寫進去的提示詞**——「你是此專案的⋯」「請完成以下
任務：」。那些字必須被剝掉，不然每一個對話的標題都會變成同一句話。

要剝掉它，比對的字就得**跟 `prompt_builder` 實際送出去的一模一樣**。
所以這一份的內容是**由提示詞決定的，不是由介面語言決定的**：

* 提示詞換一種寫法 → 這裡要跟著換
* 介面翻成英文 → 這裡**不准動**（舊的對話紀錄裡還是中文）

2026-08-24 之前這些字散在 `session_panel` 的三個地方，而它們跟
`prompt_builder` 之間沒有任何連結——**改了提示詞不會有任何東西提醒你
回來改這裡**，而症狀是所有對話標題慢慢退化成同一句開場白。

## 有三個比不到任何東西

搬過來的時候一個一個去比對 `prompt_builder`，量到 `任務要求`、
`請完成以下修正`、`技術審查` **在今天的提示詞裡一次都不出現**。

它們留著，理由寫在 `LEGACY` 裡：使用者硬碟上的舊對話紀錄是**用舊版
AICC 寫的**，那些字還在那裡。剝除規則要涵蓋歷史，不是只涵蓋現況。

**但它們現在是明著標成「歷史」的**，而不是混在現行的裡面看起來一樣有效。
"""
from __future__ import annotations

# 今天的 `prompt_builder` 真的會寫出來的開場白。
# `tests/test_prompt_markers_still_match.py` 會在對不上的時候變紅。
CURRENT: tuple[str, ...] = (
    "你是此專案",
    "請完成以下任務",
    "原始任務",
    "審查資料",
    "判定規則",
)

# 舊版 AICC 寫過、今天不再寫的。**留著是因為使用者的舊對話紀錄裡還有它們**
# ——剝除規則要涵蓋歷史。
#
# 每一條都要寫得出「它是哪一版寫的、為什麼不再寫」；寫不出來的就該刪掉，
# 因為那表示沒有人知道它在擋什麼。
LEGACY: dict[str, str] = {
    "任務要求": "早期版本的任務開頭。今天的 prompt_builder 一次都沒有它。",
    "請完成以下修正": "早期的「修正」那一輪的開頭；現在那一輪走的是同一句「請完成以下任務」。",
    "技術審查": "早期審查提示詞的標題；現在的審查提示詞沒有標題行。",
}

# 剝掉開頭的時候要比對的完整字串（含全形／半形冒號兩種）。
#
# **兩種冒號都要**：使用者的對話紀錄橫跨好幾版 AICC，而其中一版用的是
# 半形。只比一種的話，那一版寫的紀錄會整段留著開場白。
def opening_markers() -> tuple[str, ...]:
    out: list[str] = []
    for stem in ("請完成以下任務", "原始任務", "任務要求"):
        out.append(f"{stem}：")
        out.append(f"{stem}:")
    out.append(TASK_HEADING)
    return tuple(out)


def is_boilerplate(text: str) -> bool:
    """這一行整行都是 AICC 自己的開場白嗎。"""
    return any(marker in text for marker in (*CURRENT, *LEGACY))


