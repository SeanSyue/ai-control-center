"""中文特有的搜尋機制。**這裡的字不是介面文字，是斷詞用的資料。**

## 為什麼要一個自己的家

`project_knowledge` 從使用者的任務描述裡挑關鍵字，拿去查文件索引。中文沒有
空格，所以它用一個「兩到八個漢字」的樣式切，然後把**沒有資訊量的詞**丟掉
——「這個」「那個」「請幫我」查什麼都會中。

那份停用詞**不是翻譯的對象**：

* 介面翻成英文，中文的停用詞**還是要留著**（使用者的舊任務描述是中文的，
  而索引裡的文件也是）
* 真的要支援英文查詢，做的是**再加一份英文停用詞**，不是把這一份換掉

**加一份，不是換一份**——這就是它跟 `app/i18n.py` 的差別。

## 這份清單是怎麼來的

從實際用過的任務描述裡挑出來的：查「請幫我修改這個功能」的時候，
「修改」「功能」「這個」全部命中一百份文件，而真正該中的那個詞被淹掉。
"""
from __future__ import annotations

import re

# 中文的「兩到八個漢字」或英文的識別字。**不是拿來給人看的。**
TERM_PATTERN = re.compile(r"[A-Za-z_][A-Za-z0-9_.\-]{2,}|[\u4e00-\u9fff]{2,8}")

# 查什麼都會中的詞。丟掉它們之後，剩下的才是真的在指某個東西。
STOP_WORDS: frozenset[str] = frozenset({
    "請幫我",
    "請完成",
    "這個",
    "那個",
    "可以",
    "需要",
    "目前",
    "專案",
    "修改",
    "新增",
    "功能",
    "檔案",
    "不要",
    "以及",
    "然後",
})


# 一次查詢最多帶幾個詞。
MAX_TERMS = 20


def terms(query: str) -> list[str]:
    """從一句話裡挑出值得拿去查的詞。**順序保留、不重複、最多 20 個。**

    順序保留是因為使用者先講的通常比較重要。去重用 casefold，
    所以 `KYC` 與 `kyc` 只留第一個。

    ## 這一支有一個已知的弱點，**搬家的時候刻意沒有動它**

    那個樣式是**貪婪的 2~8 個漢字**，所以「請幫我修改這個功能」會被切成
    一個八字的塊，而停用詞比對的是**整個 token**——於是那份停用詞只在
    查詢短到剛好等於某個停用詞的時候才會命中。

    也就是說：**這份停用詞今天做的事比它看起來少很多。**

    這是搬過來之前就有的行為（`project_knowledge._query_terms`），
    而搬家的時候改行為，出了事會分不清是搬壞的還是本來就壞的。
    要修的話單獨一輪，而且要先量「修之前查得到什麼、修之後查得到什麼」。
    """
    result: list[str] = []
    seen: set[str] = set()
    for token in TERM_PATTERN.findall(query or ""):
        lowered = token.casefold()
        if token in STOP_WORDS or lowered in seen:
            continue
        seen.add(lowered)
        result.append(token)
    return result[:MAX_TERMS]
